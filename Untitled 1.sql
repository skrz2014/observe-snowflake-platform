USE SCHEMA GOLD;

CREATE OR REPLACE DYNAMIC TABLE DT_SERVICE_HEALTH_SCORE
    TARGET_LAG = '5 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
    SELECT
        DATE_TRUNC('HOUR', m.METRIC_TIMESTAMP) AS HOUR_BUCKET,
        m.SERVICE_NAME,
        m.ENVIRONMENT,
        m.REGION,
        COUNT(DISTINCT CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.INGESTION_ID END) AS REQUEST_COUNT,
        AVG(CASE WHEN m.METRIC_NAME = 'http.request.duration' THEN m.METRIC_VALUE END) AS AVG_LATENCY_MS,
        SUM(CASE WHEN m.METRIC_NAME = 'http.request.error_count' THEN m.METRIC_VALUE ELSE 0 END) AS ERROR_COUNT,
        CASE
            WHEN SUM(CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.METRIC_VALUE ELSE 0 END) = 0 THEN 0
            ELSE 1.0 - (SUM(CASE WHEN m.METRIC_NAME = 'http.request.error_count' THEN m.METRIC_VALUE ELSE 0 END) /
                        NULLIF(SUM(CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.METRIC_VALUE ELSE 0 END), 0))
        END AS SUCCESS_RATE,
        GREATEST(0, LEAST(100,
            (COALESCE(1.0 - (SUM(CASE WHEN m.METRIC_NAME = 'http.request.error_count' THEN m.METRIC_VALUE ELSE 0 END) /
                NULLIF(SUM(CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.METRIC_VALUE ELSE 0 END), 0)), 1) * 40) +
            (CASE WHEN AVG(CASE WHEN m.METRIC_NAME = 'http.request.duration' THEN m.METRIC_VALUE END) < 200 THEN 30
                  WHEN AVG(CASE WHEN m.METRIC_NAME = 'http.request.duration' THEN m.METRIC_VALUE END) < 500 THEN 20
                  WHEN AVG(CASE WHEN m.METRIC_NAME = 'http.request.duration' THEN m.METRIC_VALUE END) < 1000 THEN 10
                  ELSE 0 END) +
            (CASE WHEN SUM(CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.METRIC_VALUE ELSE 0 END) > 100 THEN 30
                  WHEN SUM(CASE WHEN m.METRIC_NAME = 'http.request.count' THEN m.METRIC_VALUE ELSE 0 END) > 10 THEN 20
                  ELSE 10 END)
        )) AS HEALTH_SCORE
    FROM OBSERVABILITY_PLATFORM.SILVER.DT_ENRICHED_METRICS m
    WHERE m.METRIC_TIMESTAMP >= DATEADD('DAY', -7, CURRENT_TIMESTAMP())
    GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE DT_INCIDENT_METRICS
    TARGET_LAG = '5 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
    SELECT
        DATE_TRUNC('DAY', l.LOG_TIMESTAMP) AS INCIDENT_DATE,
        l.SERVICE_NAME,
        l.ENVIRONMENT,
        COUNT(CASE WHEN l.SEVERITY IN ('ERROR', 'FATAL', 'CRITICAL') THEN 1 END) AS ERROR_COUNT,
        COUNT(DISTINCT l.TRACE_ID) AS AFFECTED_TRACES,
        MIN(l.LOG_TIMESTAMP) AS FIRST_ERROR_AT,
        MAX(l.LOG_TIMESTAMP) AS LAST_ERROR_AT,
        DATEDIFF('MINUTE', MIN(l.LOG_TIMESTAMP), MAX(l.LOG_TIMESTAMP)) AS DURATION_MINUTES,
        COUNT(DISTINCT l.HOST) AS AFFECTED_HOSTS
    FROM OBSERVABILITY_PLATFORM.SILVER.DT_ENRICHED_LOGS l
    WHERE l.SEVERITY IN ('ERROR', 'FATAL', 'CRITICAL')
        AND l.LOG_TIMESTAMP >= DATEADD('DAY', -30, CURRENT_TIMESTAMP())
    GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE DT_SLO_COMPLIANCE
    TARGET_LAG = '10 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
    SELECT
        DATE_TRUNC('DAY', t.START_TIME) AS SLO_DATE,
        t.SERVICE_NAME,
        t.ENVIRONMENT,
        COUNT(*) AS TOTAL_REQUESTS,
        SUM(CASE WHEN t.IS_ERROR THEN 1 ELSE 0 END) AS FAILED_REQUESTS,
        SUM(CASE WHEN t.DURATION_MS > 2000 THEN 1 ELSE 0 END) AS SLOW_REQUESTS,
        1.0 - (SUM(CASE WHEN t.IS_ERROR THEN 1 ELSE 0 END)::FLOAT / NULLIF(COUNT(*), 0)) AS AVAILABILITY_SLI,
        1.0 - (SUM(CASE WHEN t.DURATION_MS > 2000 THEN 1 ELSE 0 END)::FLOAT / NULLIF(COUNT(*), 0)) AS LATENCY_SLI,
        AVG(t.DURATION_MS) AS P50_LATENCY,
        APPROX_PERCENTILE(t.DURATION_MS, 0.95) AS P95_LATENCY,
        APPROX_PERCENTILE(t.DURATION_MS, 0.99) AS P99_LATENCY
    FROM OBSERVABILITY_PLATFORM.SILVER.DT_ENRICHED_TRACES t
    WHERE t.IS_ROOT_SPAN = TRUE
        AND t.START_TIME >= DATEADD('DAY', -30, CURRENT_TIMESTAMP())
    GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE DT_COST_ANALYTICS
    TARGET_LAG = '30 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
    SELECT
        DATE_TRUNC('DAY', s.EVENT_TIMESTAMP) AS COST_DATE,
        s.WAREHOUSE_NAME,
        s.USER_NAME,
        s.ROLE_NAME,
        COUNT(DISTINCT s.QUERY_ID) AS QUERY_COUNT,
        SUM(s.CREDITS_USED) AS TOTAL_CREDITS,
        AVG(s.EXECUTION_TIME_MS) AS AVG_EXECUTION_MS,
        SUM(s.BYTES_SCANNED) AS TOTAL_BYTES_SCANNED,
        SUM(s.ROWS_PRODUCED) AS TOTAL_ROWS_PRODUCED,
        SUM(CASE WHEN s.ERROR_CODE IS NOT NULL THEN 1 ELSE 0 END) AS FAILED_QUERIES,
        SUM(s.CREDITS_USED) / NULLIF(COUNT(DISTINCT s.QUERY_ID), 0) AS CREDITS_PER_QUERY
    FROM OBSERVABILITY_PLATFORM.RAW_TELEMETRY.RAW_SNOWFLAKE_TELEMETRY s
    WHERE s.TELEMETRY_TYPE = 'QUERY_HISTORY'
        AND s.EVENT_TIMESTAMP >= DATEADD('DAY', -90, CURRENT_TIMESTAMP())
    GROUP BY ALL;

