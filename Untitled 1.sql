USE SCHEMA SILVER;

CREATE OR REPLACE DYNAMIC TABLE DT_ENRICHED_LOGS
    TARGET_LAG = '5 minutes'
    WAREHOUSE = TRANSFORM_WH
    REFRESH_MODE = INCREMENTAL
AS
    SELECT
        r.INGESTION_ID,
        r.LOG_TIMESTAMP,
        r.SEVERITY,
        r.SERVICE_NAME,
        r.ENVIRONMENT,
        r.REGION,
        r.TRACE_ID,
        r.SPAN_ID,
        r.HOST,
        r.CONTAINER_ID,
        r.POD_NAME,
        r.NAMESPACE,
        r.LOG_MESSAGE,
        r.STRUCTURED_DATA,
        r.RESOURCE_ATTRIBUTES,
        CASE
            WHEN r.SEVERITY IN ('FATAL', 'CRITICAL', 'EMERGENCY') THEN 1
            WHEN r.SEVERITY = 'ERROR' THEN 2
            WHEN r.SEVERITY = 'WARN' THEN 3
            WHEN r.SEVERITY = 'INFO' THEN 4
            WHEN r.SEVERITY = 'DEBUG' THEN 5
            ELSE 6
        END AS SEVERITY_RANK,
        DATE_TRUNC('HOUR', r.LOG_TIMESTAMP) AS LOG_HOUR,
        DATE_TRUNC('DAY', r.LOG_TIMESTAMP) AS LOG_DATE,
        LENGTH(r.LOG_MESSAGE) AS MESSAGE_LENGTH,
        CONTAINS(LOWER(r.LOG_MESSAGE), 'error') OR
        CONTAINS(LOWER(r.LOG_MESSAGE), 'exception') OR
        CONTAINS(LOWER(r.LOG_MESSAGE), 'failed') AS IS_ERROR_INDICATOR
    FROM OBSERVABILITY_PLATFORM.RAW_TELEMETRY.RAW_LOGS r
    WHERE r.LOG_TIMESTAMP >= DATEADD('DAY', -90, CURRENT_TIMESTAMP());

CREATE OR REPLACE DYNAMIC TABLE DT_ENRICHED_METRICS
    TARGET_LAG = '2 minutes'
    WAREHOUSE = TRANSFORM_WH
    REFRESH_MODE = INCREMENTAL
AS
    SELECT
        r.INGESTION_ID,
        r.METRIC_TIMESTAMP,
        r.METRIC_NAME,
        r.METRIC_TYPE,
        r.METRIC_VALUE,
        r.METRIC_UNIT,
        r.SERVICE_NAME,
        r.ENVIRONMENT,
        r.REGION,
        r.HOST,
        r.DIMENSIONS,
        r.RESOURCE_ATTRIBUTES,
        DATE_TRUNC('MINUTE', r.METRIC_TIMESTAMP) AS METRIC_MINUTE,
        DATE_TRUNC('HOUR', r.METRIC_TIMESTAMP) AS METRIC_HOUR,
        DATE_TRUNC('DAY', r.METRIC_TIMESTAMP) AS METRIC_DATE
    FROM OBSERVABILITY_PLATFORM.RAW_TELEMETRY.RAW_METRICS r
    WHERE r.METRIC_TIMESTAMP >= DATEADD('DAY', -365, CURRENT_TIMESTAMP());

CREATE OR REPLACE DYNAMIC TABLE DT_ENRICHED_TRACES
    TARGET_LAG = '2 minutes'
    WAREHOUSE = TRANSFORM_WH
    REFRESH_MODE = INCREMENTAL
AS
    SELECT
        r.TRACE_ID,
        r.SPAN_ID,
        r.PARENT_SPAN_ID,
        r.SPAN_NAME,
        r.SPAN_KIND,
        r.SERVICE_NAME,
        r.ENVIRONMENT,
        r.REGION,
        r.START_TIME,
        r.END_TIME,
        r.DURATION_MS,
        r.STATUS_CODE,
        r.STATUS_MESSAGE,
        r.SPAN_ATTRIBUTES,
        r.RESOURCE_ATTRIBUTES,
        r.EVENTS,
        r.LINKS,
        CASE
            WHEN r.STATUS_CODE = 'ERROR' THEN TRUE
            ELSE FALSE
        END AS IS_ERROR,
        CASE
            WHEN r.PARENT_SPAN_ID IS NULL THEN TRUE
            ELSE FALSE
        END AS IS_ROOT_SPAN,
        CASE
            WHEN r.DURATION_MS > 5000 THEN 'CRITICAL'
            WHEN r.DURATION_MS > 2000 THEN 'SLOW'
            WHEN r.DURATION_MS > 1000 THEN 'MODERATE'
            ELSE 'NORMAL'
        END AS LATENCY_BUCKET,
        DATE_TRUNC('HOUR', r.START_TIME) AS TRACE_HOUR
    FROM OBSERVABILITY_PLATFORM.RAW_TELEMETRY.RAW_TRACES r
    WHERE r.START_TIME >= DATEADD('DAY', -30, CURRENT_TIMESTAMP());

