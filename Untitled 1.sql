        t.SERVICE_NAME AS SOURCE_SERVICE,
        t.SPAN_ATTRIBUTES:"peer.service"::VARCHAR AS TARGET_SERVICE,
        t.SPAN_KIND AS CALL_TYPE,
        COUNT(*) AS CALL_COUNT,
        AVG(t.DURATION_MS) AS AVG_LATENCY_MS,
        SUM(CASE WHEN t.IS_ERROR THEN 1 ELSE 0 END)::FLOAT / NULLIF(COUNT(*), 0) AS ERROR_RATE,
        MIN(t.START_TIME) AS FIRST_SEEN,
        MAX(t.START_TIME) AS LAST_SEEN
    FROM OBSERVABILITY_PLATFORM.SILVER.DT_ENRICHED_TRACES t
    WHERE t.SPAN_ATTRIBUTES:"peer.service" IS NOT NULL
        AND t.START_TIME >= DATEADD('DAY', -7, CURRENT_TIMESTAMP())
    GROUP BY ALL;

