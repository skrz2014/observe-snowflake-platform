-- Alert evaluation task
CREATE OR REPLACE TASK EVALUATE_ALERTS
    WAREHOUSE = AI_SRE_WH
    SCHEDULE = '1 MINUTE'
AS
    INSERT INTO OBSERVABILITY_PLATFORM.ALERTING.ALERT_HISTORY (
        RULE_ID, RULE_NAME, SEVERITY, SERVICE_NAME,
        METRIC_VALUE, THRESHOLD_VALUE, ALERT_MESSAGE
    )
    SELECT
        ar.RULE_ID,
        ar.RULE_NAME,
        ar.SEVERITY,
        ar.SERVICE_NAME,
        sh.HEALTH_SCORE AS METRIC_VALUE,
        ar.THRESHOLD_VALUE,
        'Service ' || ar.SERVICE_NAME || ' health score dropped to ' || sh.HEALTH_SCORE::VARCHAR
    FROM OBSERVABILITY_PLATFORM.ALERTING.ALERT_RULES ar
    JOIN OBSERVABILITY_PLATFORM.GOLD.DT_SERVICE_HEALTH_SCORE sh
        ON ar.SERVICE_NAME = sh.SERVICE_NAME
    WHERE ar.IS_ENABLED = TRUE
        AND ar.METRIC_NAME = 'health_score'
        AND sh.HEALTH_SCORE < ar.THRESHOLD_VALUE
        AND sh.HOUR_BUCKET = DATE_TRUNC('HOUR', CURRENT_TIMESTAMP())
        AND (ar.LAST_TRIGGERED_AT IS NULL OR
             DATEDIFF('MINUTE', ar.LAST_TRIGGERED_AT, CURRENT_TIMESTAMP()) > ar.COOLDOWN_MINUTES);

ALTER TASK EVALUATE_ALERTS RESUME;

