USE SCHEMA COST_OPS;

CREATE OR REPLACE VIEW V_DAILY_CREDIT_CONSUMPTION AS
    SELECT
        DATE_TRUNC('DAY', START_TIME) AS USAGE_DATE,
        WAREHOUSE_NAME,
        SUM(CREDITS_USED) AS CREDITS_USED,
        SUM(CREDITS_USED_COMPUTE) AS COMPUTE_CREDITS,
        SUM(CREDITS_USED_CLOUD_SERVICES) AS CLOUD_SERVICES_CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= DATEADD('DAY', -90, CURRENT_TIMESTAMP())
    GROUP BY ALL
    ORDER BY USAGE_DATE DESC, CREDITS_USED DESC;

CREATE OR REPLACE VIEW V_AI_SERVICES_COST AS
    SELECT
        USAGE_DATE,
        SERVICE_TYPE,
        SUM(CREDITS_USED) AS CREDITS_USED
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
    WHERE SERVICE_TYPE = 'AI_SERVICES'
        AND USAGE_DATE >= DATEADD('DAY', -90, CURRENT_DATE())
    GROUP BY ALL
    ORDER BY USAGE_DATE DESC;

CREATE OR REPLACE VIEW V_STORAGE_COST_ANALYSIS AS
    SELECT
        TABLE_CATALOG AS DATABASE_NAME,
        TABLE_SCHEMA AS SCHEMA_NAME,
        TABLE_NAME,
        ACTIVE_BYTES / POWER(1024, 3) AS ACTIVE_SIZE_GB,
        TIME_TRAVEL_BYTES / POWER(1024, 3) AS TIME_TRAVEL_GB,
        FAILSAFE_BYTES / POWER(1024, 3) AS FAILSAFE_GB,
        (ACTIVE_BYTES + TIME_TRAVEL_BYTES + FAILSAFE_BYTES) / POWER(1024, 3) AS TOTAL_SIZE_GB,
        TABLE_CREATED
    FROM SNOWFLAKE.ACCOUNT_USAGE.TABLE_STORAGE_METRICS
    WHERE TABLE_CATALOG = 'OBSERVABILITY_PLATFORM'
        AND DELETED IS NULL
    ORDER BY ACTIVE_BYTES DESC;
